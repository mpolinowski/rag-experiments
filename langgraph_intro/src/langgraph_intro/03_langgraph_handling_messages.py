from typing import Annotated
from pydantic import SecretStr
from operator import add

from pydantic import BaseModel, Field
from langchain_openai import ChatOpenAI
from langgraph.graph import StateGraph, START, END
from langchain_core.messages import HumanMessage, SystemMessage, AIMessage

client = ChatOpenAI(
    model="qwen3.8:latest",
    temperature=0.6,
    top_p=0.95,
    base_url="http://localhost:11434/v1",
    api_key=SecretStr("ollama"),
)

# print(client.invoke([HumanMessage(content="Tell me an Haiku that sums up the popular television show 'Lost'.")]))

# Create structured Schema

class graph_shema(BaseModel):
    messages_system: SystemMessage = Field(description="This is the system message that is being added to every prompt.")
    # If you want to append messages here instead of overwriting you have to do it manually
    messages_manual: list = Field(description="This is the list of messages that get appended manually (no add reducer).")
    # 'messages_auto' use the add operator to make sure that new messages are automatically appened
    messages_auto: Annotated[list, add] = Field(description="This is the list of auto-added AI messages generated by the llm.")

demo = graph_shema(
    messages_system=SystemMessage(content="You are a helpful agent."),
    messages_manual=[HumanMessage(content="Tell me about yourself.")],
    messages_auto=["What do you think about?"]
)

# Create Node functions

def generate_text(state: graph_shema) -> graph_shema:

    messages_manual = list(state.messages_manual)
    messages_auto = list(state.messages_auto)

    # 'manual' = no reducer, so we append to the list explicitly
    messages_manual.append(AIMessage(content=client.invoke(messages_manual).content))
    state.messages_manual = messages_manual

    response_auto_ai = [AIMessage(content=client.invoke(messages_auto).content)]
    state.messages_auto = response_auto_ai

    return state

def process_text(state: graph_shema) -> graph_shema:
    messages_manual = list(state.messages_manual)

    response_manual = client.invoke(messages_manual).content
    messages_manual.append(AIMessage(content=client.invoke(response_manual).content))
    state.messages_manual = messages_manual

    return state

# Create the State Graph

## Adding Nodes
graph = StateGraph(graph_shema)
graph.add_node("generate_text", generate_text)
graph.add_node("process_text", process_text)
## Adding Edges
graph.add_edge(START, "generate_text")
graph.add_edge("generate_text", "process_text")
graph.add_edge("process_text", END)
graph = graph.compile()

# Run Graph

response = graph.invoke(demo) # expects graph_shema!

print(response)
